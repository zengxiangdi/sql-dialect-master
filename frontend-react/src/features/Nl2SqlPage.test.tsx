import { act, cleanup, fireEvent, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { MemoryRouter } from "react-router-dom";
import { afterEach, describe, expect, it, vi } from "vitest";
import { Nl2SqlPage } from "./Nl2SqlPage";

function renderPage() {
  return render(<MemoryRouter initialEntries={["/nl2sql"]}><Nl2SqlPage /></MemoryRouter>);
}

function response(payload: unknown) {
  return { ok: true, status: 200, headers: new Headers(), json: async () => payload };
}

function deferred<T>() {
  let resolve!: (value: T) => void;
  const promise = new Promise<T>((resolvePromise) => { resolve = resolvePromise; });
  return { promise, resolve };
}

const generatedResult = {
  success: true, input_text: "list orders", sql: "SELECT id FROM orders", dialect: "postgres",
  explanation: "Generated by the configured LLM.", confidence: 0.8, suggestions: [],
  provider: "llm", model: "configured-model", schema_used: true,
};

describe("natural language query form", () => {
  afterEach(() => {
    cleanup();
    localStorage.clear();
    vi.unstubAllGlobals();
    vi.restoreAllMocks();
  });

  it("fills the editable natural-language field from an example without generating a request", async () => {
    const fetchMock = vi.fn();
    vi.stubGlobal("fetch", fetchMock);
    const user = userEvent.setup();
    renderPage();

    const input = screen.getByRole("textbox", { name: "Natural language" });
    const generate = screen.getByRole("button", { name: "Generate SQL" });
    expect(input).toHaveClass("nl-input");
    expect(input).toHaveValue("");
    expect(generate).toBeDisabled();

    const example = screen.getByRole("button", { name: "Find the top 10 customers by revenue" });
    expect(example).toHaveClass("example-chip");
    await user.click(example);
    expect(input).toHaveValue("Find the top 10 customers by revenue");
    expect(generate).toBeEnabled();

    await user.clear(input);
    await user.type(input, "   ");
    expect(generate).toBeDisabled();
    await user.clear(input);
    await user.type(input, "List paid orders");
    expect(input).toHaveValue("List paid orders");
    expect(generate).toBeEnabled();
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("preserves dialect and hints in the request and displays generated SQL, explanation, and evidence", async () => {
    const result = {
      success: true,
      input_text: "List paid orders by id",
      sql: "SELECT id FROM orders WHERE status = 'paid'",
      dialect: "mysql",
      explanation: "Select paid orders using the supplied table and column hints.",
      confidence: 0.93,
      suggestions: [],
      evidence: { matched_columns: ["orders.id", "orders.status"] },
      parameters: [],
      parameter_style: null,
    };
    const fetchMock = vi.fn().mockResolvedValue({
      ok: true, status: 200, headers: new Headers(), json: async () => result,
    });
    vi.stubGlobal("fetch", fetchMock);
    const user = userEvent.setup();
    renderPage();

    await user.click(screen.getByRole("button", { name: "Find the top 10 customers by revenue" }));
    const input = screen.getByRole("textbox", { name: "Natural language" });
    await user.clear(input);
    await user.type(input, result.input_text);
    await user.selectOptions(screen.getByRole("combobox", { name: "Target dialect" }), "mysql");
    await user.type(screen.getByRole("textbox", { name: /Table hint/ }), "orders");
    await user.type(screen.getByRole("textbox", { name: "Column hints" }), " orders.id, , orders.status ");
    await user.click(screen.getByRole("button", { name: "Generate SQL" }));

    const output = await screen.findByRole("textbox", { name: "Generated SQL" });
    expect(output).toHaveValue(result.sql);
    expect(output).toHaveAttribute("readonly");
    expect(output).toHaveClass("code-editor");
    expect(output.closest(".nl-result-card")).toBeInTheDocument();
    expect(screen.getByText(result.explanation)).toBeInTheDocument();
    expect(screen.getByText("93% confidence")).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Use in Convert" })).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Use in Diff" })).toBeInTheDocument();

    expect(fetchMock).toHaveBeenCalledTimes(1);
    const [url, request] = fetchMock.mock.calls[0] as [string, RequestInit];
    expect(url).toBe("/api/nl2sql");
    expect(request.method).toBe("POST");
    expect(request.signal).toBeInstanceOf(AbortSignal);
    expect(JSON.parse(request.body as string)).toEqual({
      text: result.input_text,
      dialect: "mysql",
      table_hint: "orders",
      column_hints: ["orders.id", "orders.status"],
      schema: null,
    });

    const evidence = screen.getByText("Evidence and parameters");
    await user.click(evidence);
    const details = evidence.closest("details");
    expect(details).toHaveAttribute("open");
    const json = details?.querySelector(".json-block");
    expect(json).toBeInTheDocument();
    expect(JSON.parse(json?.textContent || "")).toEqual({
      evidence: result.evidence,
      parameters: result.parameters,
      parameter_style: result.parameter_style,
    });
  });

  it.each([
    { metadata: { provider: "llm", model: "openai/gpt-4.1-mini" }, label: "LLM · openai/gpt-4.1-mini" },
    { metadata: { provider: "deterministic", model: null }, label: "Deterministic" },
    { metadata: {}, label: "Deterministic" },
    { metadata: { provider: "llm", model: null }, label: "LLM" },
  ])("shows $label beside confidence for provider metadata $metadata", async ({ metadata, label }) => {
    const result = {
      success: true, input_text: "count orders", sql: "SELECT COUNT(*) FROM orders", dialect: "postgres",
      explanation: "Count the supplied table.", confidence: 0.9, suggestions: [], ...metadata,
    };
    vi.stubGlobal("fetch", vi.fn().mockResolvedValue({
      ok: true, status: 200, headers: new Headers(), json: async () => result,
    }));
    const user = userEvent.setup();
    renderPage();
    await user.type(screen.getByRole("textbox", { name: "Natural language" }), result.input_text);
    await user.click(screen.getByRole("button", { name: "Generate SQL" }));

    const provider = await screen.findByText(label);
    expect(provider).toHaveClass("badge-neutral");
    expect(provider.parentElement).toContainElement(screen.getByText("90% confidence"));
    expect(screen.getByRole("textbox", { name: "Generated SQL" })).toHaveValue(result.sql);
    expect(screen.queryByRole("status")).not.toBeInTheDocument();
  });

  it("uses a generic fallback hint without displaying an unknown provider failure reason", async () => {
    const rawReason = "upstream_error: private-provider-diagnostic";
    const result = {
      success: true, input_text: "count orders", sql: "SELECT COUNT(*) FROM orders", dialect: "postgres",
      explanation: "Count the supplied table.", confidence: 0.9, suggestions: [],
      provider: "deterministic", model: null, fallback_reason: rawReason,
    };
    vi.stubGlobal("fetch", vi.fn().mockResolvedValue({
      ok: true, status: 200, headers: new Headers(), json: async () => result,
    }));
    const user = userEvent.setup();
    renderPage();
    await user.type(screen.getByRole("textbox", { name: "Natural language" }), result.input_text);
    await user.click(screen.getByRole("button", { name: "Generate SQL" }));

    expect(await screen.findByRole("status")).toHaveTextContent("LLM generation was unavailable; deterministic generation was used.");
    expect(screen.getByText("Deterministic")).toBeInTheDocument();
    expect(screen.queryByText(rawReason)).not.toBeInTheDocument();
    expect(document.body).not.toHaveTextContent(rawReason);
    expect(screen.getByRole("textbox", { name: "Generated SQL" })).toHaveValue(result.sql);
    expect(screen.getByRole("button", { name: "Use in Convert" })).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Use in Diff" })).toBeInTheDocument();
  });

  it.each([
    ["timeout", "LLM timed out; deterministic generation was used."],
    ["http_429", "LLM rate limit reached; deterministic generation was used."],
    ["http_5xx", "LLM provider is unavailable; deterministic generation was used."],
    ["http_error", "LLM provider request failed; deterministic generation was used."],
    ["invalid_sql", "LLM output did not pass SQL validation; deterministic generation was used."],
    ["invalid_response", "LLM returned an unusable response; deterministic generation was used."],
    ["empty_content", "LLM returned an empty response; deterministic generation was used."],
    ["disabled", "LLM is not enabled; deterministic generation was used."],
    ["constructor", "LLM generation was unavailable; deterministic generation was used."],
  ])("explains the %s fallback using a fixed status message", async (reason, message) => {
    const fetchMock = vi.fn().mockResolvedValue(response({
      ...generatedResult, provider: "deterministic", model: null, schema_used: false, fallback_reason: reason,
    }));
    vi.stubGlobal("fetch", fetchMock);
    renderPage();
    fireEvent.change(screen.getByRole("textbox", { name: "Natural language" }), { target: { value: generatedResult.input_text } });
    fireEvent.click(screen.getByRole("button", { name: "Generate SQL" }));

    expect(await screen.findByRole("status")).toHaveTextContent(message);
    expect(screen.getByText("Deterministic")).toBeInTheDocument();
    expect(screen.queryByText("Schema-grounded")).not.toBeInTheDocument();
    expect(fetchMock).toHaveBeenCalledTimes(1);
  });

  it("copies the generated SQL with the shared Copy button without sending another request", async () => {
    const fetchMock = vi.fn().mockResolvedValue(response(generatedResult));
    vi.stubGlobal("fetch", fetchMock);
    const user = userEvent.setup();
    const writeText = vi.spyOn(navigator.clipboard, "writeText").mockResolvedValue();
    renderPage();
    expect(screen.queryByRole("button", { name: "Copy" })).not.toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Regenerate" })).not.toBeInTheDocument();
    await user.type(screen.getByRole("textbox", { name: "Natural language" }), generatedResult.input_text);
    await user.click(screen.getByRole("button", { name: "Generate SQL" }));
    await user.click(await screen.findByRole("button", { name: "Copy" }));

    expect(writeText).toHaveBeenCalledExactlyOnceWith(generatedResult.sql);
    expect(await screen.findByRole("button", { name: "Copied" })).toBeInTheDocument();
    expect(fetchMock).toHaveBeenCalledTimes(1);
  });

  it("regenerates once with the same inputs and disables generation actions until completion", async () => {
    const pending = deferred<ReturnType<typeof response>>();
    const nextResult = { ...generatedResult, sql: "SELECT id FROM orders LIMIT 10", dialect: "mysql" };
    const fetchMock = vi.fn()
      .mockResolvedValueOnce(response({ ...generatedResult, dialect: "mysql" }))
      .mockReturnValueOnce(pending.promise);
    vi.stubGlobal("fetch", fetchMock);
    const user = userEvent.setup();
    const schemaText = JSON.stringify({ tables: [{ name: "orders", columns: [{ name: "id" }] }] });
    renderPage();
    await user.type(screen.getByRole("textbox", { name: "Natural language" }), generatedResult.input_text);
    await user.selectOptions(screen.getByRole("combobox", { name: "Target dialect" }), "mysql");
    await user.type(screen.getByRole("textbox", { name: /Table hint/ }), "orders");
    await user.type(screen.getByRole("textbox", { name: "Column hints" }), "orders.id");
    await user.click(screen.getByText("Schema (optional JSON)"));
    fireEvent.change(screen.getByRole("textbox", { name: "Schema JSON" }), { target: { value: schemaText } });
    await user.click(screen.getByRole("button", { name: "Generate SQL" }));
    const regenerate = await screen.findByRole("button", { name: "Regenerate" });
    expect(regenerate).toBeEnabled();
    await user.click(regenerate);

    expect(fetchMock).toHaveBeenCalledTimes(2);
    const firstBody = JSON.parse(fetchMock.mock.calls[0][1].body);
    expect(firstBody).toEqual({
      text: generatedResult.input_text, dialect: "mysql", table_hint: "orders", column_hints: ["orders.id"], schema: JSON.parse(schemaText),
    });
    expect(JSON.parse(fetchMock.mock.calls[1][1].body)).toEqual(firstBody);
    expect(regenerate).toBeDisabled();
    expect(regenerate).toHaveAttribute("aria-busy", "true");
    expect(screen.getByRole("button", { name: "Generate SQL" })).toBeDisabled();
    expect(screen.getByRole("textbox", { name: "Natural language" })).toHaveValue(generatedResult.input_text);
    expect(screen.getByRole("combobox", { name: "Target dialect" })).toHaveValue("mysql");
    expect(screen.getByRole("textbox", { name: /Table hint/ })).toHaveValue("orders");
    expect(screen.getByRole("textbox", { name: "Column hints" })).toHaveValue("orders.id");
    expect(screen.getByRole("textbox", { name: "Schema JSON" })).toHaveValue(schemaText);
    await user.click(regenerate);
    await user.click(screen.getByRole("button", { name: "Generate SQL" }));
    expect(fetchMock).toHaveBeenCalledTimes(2);

    await act(async () => { pending.resolve(response(nextResult)); });

    expect(screen.getByRole("textbox", { name: "Generated SQL" })).toHaveValue(nextResult.sql);
    expect(screen.getByRole("button", { name: "Regenerate" })).toBeEnabled();
    expect(screen.getByRole("button", { name: "Generate SQL" })).toBeEnabled();
    expect(fetchMock).toHaveBeenCalledTimes(2);
  });

  it.each([
    ["Natural language", "list users"],
    ["Target dialect", "mysql"],
    ["Table hint", "users"],
    ["Column hints", "users.id"],
    ["Schema JSON", '{"tables":[{"name":"users"}]}'],
  ])("cancels regeneration when %s changes and ignores the stale response", async (field, value) => {
    const pending = deferred<ReturnType<typeof response>>();
    const fetchMock = vi.fn().mockResolvedValueOnce(response(generatedResult)).mockReturnValueOnce(pending.promise);
    vi.stubGlobal("fetch", fetchMock);
    renderPage();
    fireEvent.change(screen.getByRole("textbox", { name: "Natural language" }), { target: { value: generatedResult.input_text } });
    fireEvent.click(screen.getByRole("button", { name: "Generate SQL" }));
    fireEvent.click(await screen.findByRole("button", { name: "Regenerate" }));
    const signal = (fetchMock.mock.calls[1][1] as RequestInit).signal;
    expect(signal?.aborted).toBe(false);
    if (field === "Schema JSON") fireEvent.click(screen.getByText("Schema (optional JSON)"));
    const input = field === "Target dialect"
      ? screen.getByRole("combobox", { name: field })
      : screen.getByRole("textbox", { name: field === "Table hint" ? /Table hint/ : field });
    fireEvent.change(input, { target: { value } });

    expect(signal?.aborted).toBe(true);
    expect(input).toHaveValue(value);
    expect(screen.queryByRole("textbox", { name: "Generated SQL" })).not.toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Copy" })).not.toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Regenerate" })).not.toBeInTheDocument();
    await act(async () => { pending.resolve(response({ ...generatedResult, sql: "SELECT stale_result FROM orders" })); });

    expect(screen.queryByRole("textbox", { name: "Generated SQL" })).not.toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Generate SQL" })).toBeEnabled();
    expect(fetchMock).toHaveBeenCalledTimes(2);
  });

  it("keeps Copy and Regenerate hidden when generation returns no SQL and does not retry automatically", async () => {
    const fetchMock = vi.fn().mockResolvedValue(response({
      ...generatedResult, success: false, sql: null, schema_used: false, explanation: "Generation was unavailable.",
    }));
    vi.stubGlobal("fetch", fetchMock);
    renderPage();
    fireEvent.change(screen.getByRole("textbox", { name: "Natural language" }), { target: { value: generatedResult.input_text } });
    fireEvent.click(screen.getByRole("button", { name: "Generate SQL" }));

    expect(await screen.findByRole("alert")).toHaveTextContent("Generation was unavailable.");
    expect(screen.queryByRole("button", { name: "Copy" })).not.toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Regenerate" })).not.toBeInTheDocument();
    expect(fetchMock).toHaveBeenCalledTimes(1);
  });

  it("blocks malformed schema JSON locally without sending it or exposing parser details", async () => {
    const fetchMock = vi.fn();
    vi.stubGlobal("fetch", fetchMock);
    const user = userEvent.setup();
    renderPage();
    await user.type(screen.getByRole("textbox", { name: "Natural language" }), "list orders");
    const schemaSection = screen.getByText("Schema (optional JSON)");
    expect(schemaSection.closest("details")).not.toHaveAttribute("open");
    await user.click(schemaSection);
    fireEvent.change(screen.getByRole("textbox", { name: "Schema JSON" }), { target: { value: '{"tables": malformed-private-schema}' } });

    await user.click(screen.getByRole("button", { name: "Generate SQL" }));

    expect(screen.getByText("Schema must be valid JSON.")).toBeInTheDocument();
    expect(fetchMock).not.toHaveBeenCalled();
    expect(screen.getByRole("button", { name: "Generate SQL" })).toBeEnabled();
    expect(localStorage.length).toBe(0);
  });

  it("sends parsed schema, marks grounded results, and sends null after the schema is cleared", async () => {
    const schema = {
      tables: [
        { name: "orders", columns: [{ name: "id", type: "integer" }, { name: "user_id" }] },
        { name: "users", columns: [{ name: "id" }] },
      ],
      relationships: [{ from_table: "orders", from_column: "user_id", to_table: "users", to_column: "id" }],
    };
    const result = {
      success: true, input_text: "list orders", sql: "SELECT id FROM orders", dialect: "postgres",
      explanation: "Generated by the configured LLM.", confidence: 0.8, suggestions: [],
      provider: "llm", model: "configured-model", schema_used: true,
    };
    const fetchMock = vi.fn()
      .mockResolvedValueOnce({ ok: true, status: 200, headers: new Headers(), json: async () => result })
      .mockResolvedValueOnce({ ok: true, status: 200, headers: new Headers(), json: async () => ({ ...result, schema_used: false }) });
    vi.stubGlobal("fetch", fetchMock);
    const user = userEvent.setup();
    renderPage();
    await user.type(screen.getByRole("textbox", { name: "Natural language" }), result.input_text);
    await user.click(screen.getByText("Schema (optional JSON)"));
    const schemaInput = screen.getByRole("textbox", { name: "Schema JSON" });
    fireEvent.change(schemaInput, { target: { value: JSON.stringify(schema) } });
    await user.click(screen.getByRole("button", { name: "Generate SQL" }));

    const grounded = await screen.findByText("Schema-grounded");
    expect(grounded).toHaveClass("badge-neutral");
    expect(grounded.parentElement).toContainElement(screen.getByText("LLM · configured-model"));
    expect(grounded.parentElement).toContainElement(screen.getByText("80% confidence"));
    expect(screen.getByRole("textbox", { name: "Generated SQL" })).toHaveValue(result.sql);
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toEqual({
      text: result.input_text, dialect: "postgres", table_hint: null, column_hints: null, schema,
    });
    expect(localStorage.length).toBe(0);

    await user.clear(schemaInput);
    expect(screen.queryByText("Schema-grounded")).not.toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Generate SQL" }));
    await screen.findByRole("textbox", { name: "Generated SQL" });

    expect(fetchMock).toHaveBeenCalledTimes(2);
    expect(JSON.parse(fetchMock.mock.calls[1][1].body).schema).toBeNull();
    expect(screen.queryByText("Schema-grounded")).not.toBeInTheDocument();
    expect(localStorage.length).toBe(0);
  });
});
